"""Runs the whole verification of the SHA2/SHA3 hash IP and writes reports/summary.md.
Usage: python run_all.py [--skip-boot]
Steps: static checks of the RTL (rule check, lint, CSR verify), vectors, elaboration tests, regression suites,
performance, waveform evidence, coverage, evidence checks of the skill. The first command of a fresh checkout is
`python gen_vectors.py` (needs the NIST files in ref_nist/, see README.md).
"""
import os
import subprocess
import sys
import time

import simlib as S

VER = S.VER
IP = os.path.dirname(VER)
SK = 'C:/Users/PC/.claude/skills/vlsit-rtl-generator/scripts'
PY = sys.executable


def run(cmd, log=None, cwd=None):
    t = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)
    out = r.stdout + r.stderr
    if log:
        os.makedirs(os.path.dirname(log), exist_ok=True)
        open(log, 'w').write(out)
    return r.returncode, out, time.time() - t


def main():
    skip_boot = '--skip-boot' in sys.argv
    here = os.path.dirname(os.path.abspath(__file__))
    os.makedirs(VER + '/reports', exist_ok=True)
    rows = []
    def step(name, cmd, log, cwd=None, okcodes=(0,)):
        rc, out, dt = run(cmd, VER + '/logs/' + log, cwd)
        rows.append((name, 'PASS' if rc in okcodes else 'FAIL (exit %d)' % rc, '%.0f s' % dt, 'logs/' + log))
        print(rows[-1])
        return rc, out
    step('rule check of rtl/', [PY, '-I', SK + '/vlsit_rtl_check.py', 'check', IP + '/rtl'], 'static_rule_check.log')
    step('CSR generated files unedited (verify)', [PY, '-I', SK + '/vlsit_csr_generate.py', 'verify', IP + '/rtl/csr'], 'static_csr_verify.log')
    step('lint (verilator) of rtl/filelist.f', [PY, '-I', SK + '/vlsit_lint_rtl.py', 'lint', IP + '/rtl/filelist.f', '--top', 'm_vlsit_sha_top'],
         'static_lint.log', cwd=IP + '/rtl')
    step('vectors (NIST CAVP + hashlib)', [PY, 'gen_vectors.py'], 'gen_vectors.log', cwd=here)
    step('directed vectors', [PY, 'gen_directed.py'], 'gen_directed.log', cwd=here)
    step('performance vectors', [PY, 'gen_perf.py'], 'gen_perf.log', cwd=here)
    step('fault vectors', [PY, 'gen_fault.py'], 'gen_fault.log', cwd=here)
    step('context-count vectors', [PY, 'gen_ctx.py'], 'gen_ctx.log', cwd=here)
    step('masking vectors', [PY, 'gen_mask.py'], 'gen_mask.log', cwd=here)
    step('unit tests: masked core, random bit source', [PY, 'unit_mask.py'], 'unit_mask.log', cwd=here)
    step('waveform scenarios', [PY, 'gen_wf.py'], 'gen_wf.log', cwd=here)
    step('static checks TEST-023, TEST-024 (structure and names)', [PY, 'static_checks.py'], 'static_checks.log', cwd=here)
    step('X policy by random power-up state TEST-025', [PY, 'xcheck.py'], 'xcheck.log', cwd=here)
    step('elaboration tests TEST-002, TEST-015', [PY, 'elab_tests.py'], 'elab_tests.log', cwd=here)
    suites = ['main64', 'main32', 'main128', 'dma64', 'dma32', 'dma128', 'fault_dup64', 'fault_par64', 'fault_redo64', 'fault_all64',
              'mask_reg64', 'mask_reg32', 'mask_ent64', 'mask_stat64', 'mask_statctl64', 'mask_fault64', 'main64_mask',
              'perf_u1', 'perf_u2', 'perf_u4', 'perf_redo', 'perf_mask', 'limit64', 'ctx1', 'ctx2', 'ctx8', 'ctx16', 'dirctx1', 'dirctx2', 'dirctx16']
    if not skip_boot:
        suites.append('boot')
    for r in ('r1_1', 'r1_3', 'r7_2', 'r2_7'):
        suites += ['async_%s_synth' % r] + ['async_%s_seed%d' % (r, s) for s in (1, 2, 3)]
    rc, out, dt = run([PY, 'run_regress.py'] + suites, VER + '/logs/regress_driver.log', here)
    for line in out.splitlines():
        if line.startswith(tuple(suites)):
            nm = line.split(' ', 1)[0]
            rows.append(('suite ' + nm, 'PASS' if "'ok': True" in line else 'FAIL', '', line.split(' ', 1)[1][:150]))
    # share statistics (TEST-021): Welch t-test of the masked run, and the unmasked control that shall show the leak
    step('share statistics, masked run (|t| < 4.5)', [PY, 'mask_stat.py', VER + '/logs/mask_stat64.log'], 'mask_stat_masked.log', cwd=here)
    step('share statistics, control without masking (|t| >= 4.5 expected)', [PY, 'mask_stat.py', VER + '/logs/mask_statctl64.log'], 'mask_stat_control.log',
         cwd=here, okcodes=(1,))
    step('performance check TEST-018', [PY, 'perf_check.py'], 'perf_check.log', cwd=here)
    step('waveform evidence (17 scenarios)', [PY, 'wf_tool.py'], 'wf_tool.log', cwd=here)
    step('coverage report', [PY, 'cov_report.py'], 'cov_report.log', cwd=here)
    spec = IP + '/VLSIT_SHA2_SHA3_HASH_HDS.md'
    step('evidence check of the skill (waveforms and CDC logs)',
         [PY, '-I', SK + '/vlsit_sim_evidence.py', 'check', spec, VER + '/waveforms_sim', '--logs', VER + '/logs/cdc'], 'sim_evidence.log')
    lines = ['# Verification summary (generated by scripts/run_all.py)', '', '| Step | Result | Time | Where |', '|---|---|---|---|']
    for r in rows:
        lines.append('| %s | %s | %s | %s |' % r)
    open(VER + '/reports/summary.md', 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
